export function renderPipeline(session, now) {
  const link = session.linkState(now);
  const s = session.latest;
  const current = link === Link.RECEIVING;
  const active = session.diagnostics.getActive();
  const issues = active.filter((d) => d.severity !== 'info');
  const notEval = active.filter((d) => d.ruleId.endsWith('-unavailable'));
  const sensors = s ? ['solar', 'wind', 'piezo', 'battery', 'light'].filter((k) => isAvailable(s[k])).length : 0;
  const ver = session.verifier;
  const lastRes = ver.results.at(-1);
  const a = ver.active;
  const cleaner = s?.cleaner;

  const stages = [
    { id: 'sense', label: 'SENSE', lit: current, text: current ? `${sensors} of 5 sensors reporting` : LINK_TEXT[link].toLowerCase(), cls: current ? 'ok' : 'muted' },
    {
      id: 'diagnose', label: 'DIAGNOSE', lit: current,
      text: !current ? 'paused - no current data' : issues.length ? `${issues.length} active warning${issues.length > 1 ? 's' : ''}` : 'no active warnings',
      cls: !current ? 'muted' : issues.length ? 'warn' : 'ok',
      note: notEval.length ? `${notEval.length} not evaluable` : '',
    },
    {
      id: 'act', label: 'ACT', lit: current && cleaner?.state !== Cleaner.IDLE,
      text: !current || !cleaner ? 'cleaner state unknown' : cleaner.state === Cleaner.CLEANING ? 'Cleaning now (ESP32)' : cleaner.state === Cleaner.COOLDOWN ? 'Cooldown (ESP32)' : cleaner.state === Cleaner.CHECKING ? 'Confirming low output' : `Idle - ${cleaner.cycles ?? 0} cycle${cleaner.cycles === 1 ? '' : 's'}`,
      cls: cleaner?.state === Cleaner.CLEANING ? 'accent' : 'muted',
    },
    {
      id: 'verify', label: 'VERIFY', lit: Boolean(a) || Boolean(lastRes),
      text: a ? (a.phase === 'cleaning' ? 'Baseline captured' : `Collecting after-data ${a.post.length}`) : lastRes ? lastRes.outcome.toLowerCase() : 'awaiting a cycle',
      cls: a ? 'accent' : lastRes?.outcome === 'OUTPUT IMPROVED' ? 'ok' : lastRes?.outcome === 'OUTPUT DECREASED' ? 'warn' : 'muted',
    },
  ];
  setHtml(
    $('#pipeline'),
    stages
      .map((st, i) => `<div class="stage ${st.cls}" data-lit="${st.lit ? 1 : 0}"><span class="stage-n">${i + 1}</span><div><b>${st.label}</b><small>${esc(st.text)}${st.note ? ` <em>${esc(st.note)}</em>` : ''}</small></div></div>`)
      .join('<span class="stage-arrow" aria-hidden="true"></span>'),
  );
}

