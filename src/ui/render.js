const SEV_LABEL = { critical: 'CRITICAL', error: 'ERROR', warning: 'WARNING', info: 'NOTICE' };

const diagCard = (d, recovered = false) => `<li class="diag ${d.severity}${recovered ? ' recovered' : ''}">
    <div class="diag-h"><span class="sev">${SEV_LABEL[d.severity] ?? d.severity}</span><b>${esc(d.title)}</b><span class="sub-chip">${esc(d.subsystem ?? '')}</span><span class="st ${recovered ? 'rec' : 'act'}">${recovered ? 'RECOVERED' : 'ACTIVE'}</span></div>
    <p class="times">First detected ${clock(d.firstDetectedAt)} - updated ${clock(d.lastUpdatedAt)}${recovered ? ` - recovered ${clock(d.resolvedAt)}` : ''}</p>
    <p>${esc(d.explanation)}</p>
    <ul class="evidence">${d.evidence.filter(Boolean).map((e) => `<li>${esc(e)}</li>`).join('')}</ul>
    ${recovered ? '' : `<p class="action"><b>Next:</b> ${esc(d.action)}</p>`}
    <p class="recov"><b>Recovery condition:</b> ${esc(d.recovery ?? '')}</p>
    <p class="conf">${esc(d.confidence)}</p>
  </li>`;

export function renderDiagnostics(session, now) {
  const active = session.diagnostics.getActive();
  const link = session.linkState(now);
  const problems = active.filter((d) => d.severity !== 'info');
  const notices = active.filter((d) => d.severity === 'info');
  const resolved = session.diagnostics.getResolved();

  const none =
    link === Link.RECEIVING && problems.length === 0
      ? '<li class="diag-empty ok"><b>No active faults or warnings.</b><p>Every check that can be evaluated is passing. Notices (informational) are listed below.</p></li>'
      : problems.length === 0
        ? '<li class="diag-empty"><b>Diagnostics paused.</b><p>There is no current telemetry to evaluate, so no checks are being scored.</p></li>'
        : '';

  setHtml(
    $('#diagList'),
    `${none}${problems.map((d) => diagCard(d)).join('')}${notices.length ? `<li class="diag-group">Notices</li>${notices.map((d) => diagCard(d)).join('')}` : ''}${
      resolved.length ? `<li class="diag-group">Recovered incidents (${resolved.length}) - kept as history</li>${resolved.slice(0, 8).map((d) => diagCard(d, true)).join('')}` : ''
    }`,
  );
  setText($('#diagCount'), `${problems.length} active - ${resolved.length} recovered`);
}

// ---------- cleaning verification ----------

const OUTCOME_CLS = { 'OUTPUT IMPROVED': 'ok', 'NO SIGNIFICANT CHANGE': 'muted', 'OUTPUT DECREASED': 'warn' };
const outcomeClass = (o) => OUTCOME_CLS[o] ?? 'inconclusive';

function sideTile(label, v, extra = '') {
  return `<div class="vtile"><small>${label}</small><b>${fmt(v.mA, 1)}<i> mA</i></b><span>${fmt(v.V, 2)} V - ${fmt(v.mW, 0)} mW - light raw ${fmt(v.ldr, 0)}</span><span>${v.n} sample${v.n === 1 ? '' : 's'}</span>${extra}</div>`;
}

function barPair(before, after) {
  const max = Math.max(before.mA ?? 0, after.mA ?? 0, 1);
  const w = (v) => `${Math.max(2, ((v ?? 0) / max) * 100).toFixed(1)}%`;
  return `<div class="vbars"><div><span>Before</span><div class="vbar"><i style="width:${w(before.mA)}"></i></div></div><div><span>After</span><div class="vbar after"><i style="width:${w(after.mA)}"></i></div></div></div>`;
}

export function renderVerify(session, now, ui) {
  const s = session.latest;
  const link = session.linkState(now);
  const cur = link === Link.RECEIVING ? s?.cleaner?.state : null;
  const v = session.verifier;
  const a = v.active;
  const results = v.results;
  const cfg = session.config.verification;
  const idx = ui.verifyIndex !== null && ui.verifyIndex < results.length ? ui.verifyIndex : results.length - 1;
  const r = results[idx];

  const track = ['IDLE', 'CLEANING', 'COOLDOWN']
    .map((n) => `<li data-on="${cur === n || (n === 'IDLE' && cur === Cleaner.CHECKING) ? 1 : 0}" data-st="${n}"><i></i>${n}${n === 'IDLE' && cur === Cleaner.CHECKING ? '<em>confirming</em>' : ''}</li>`)
    .join('<span class="track-arrow"></span>');

  let status;
  if (a?.phase === 'cleaning') status = `Cleaning in progress (reported by ESP32). Baseline: ${a.baseline.length} sample${a.baseline.length === 1 ? '' : 's'}. ${a.trigger}`;
  else if (a?.phase === 'post') status = `Cleaning finished. Collecting after-cleaning data: ${a.post.length} of ${cfg.postSamples} samples (waits ${cfg.settleMs / 1000} s to settle).`;
  else if (cur === Cleaner.CHECKING) status = 'Firmware is confirming low output in bright light. It will start a cycle if this persists.';
  else status = results.length ? 'Waiting for the next cleaning cycle reported by the ESP32.' : 'Waiting for a cleaning cycle reported by the ESP32. Nothing is simulated or assumed.';

  let result;
  if (r) {
    const pct = r.pctMa === null ? 'n/a' : `${r.pctMa >= 0 ? '+' : ''}${fmt(r.pctMa, 0)}%`;
    const light =
      r.lightDeltaRaw === null ? 'Light unavailable' : `Light ${r.lightChanged ? 'CHANGED' : 'steady'} (${r.lightDeltaRaw >= 0 ? '+' : ''}${fmt(r.lightDeltaRaw, 0)} LDR counts)`;
    result = `<div class="vresult ${outcomeClass(r.outcome)}">
        <div class="vhead"><span class="vout">${esc(r.outcome)}</span><span class="chip q-${r.quality}">DATA QUALITY: ${r.quality}</span><time>cycle #${esc(r.cycle ?? '?')} - ${clock(r.startT)}</time></div>
        ${r.before.n && r.after.n ? `<div class="vgrid">${sideTile('BEFORE (median)', r.before)}<div class="vdelta"><b>${r.deltaMa >= 0 ? '+' : ''}${fmt(r.deltaMa, 1)}<i> mA</i></b><span>${pct}</span></div>${sideTile('AFTER (median)', r.after)}</div>${barPair(r.before, r.after)}` : '<p class="vnone">No before/after values - the comparison could not be formed.</p>'}
        <div class="vmeta"><span class="chip">${esc(light)}</span></div>
        <p class="vtrigger"><b>Why it ran:</b> ${esc(r.trigger ?? 'unknown')}</p>
        <p class="vexp">${esc(r.explanation)}</p>
        ${r.reasons.length ? `<ul class="vreasons">${r.reasons.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>` : ''}
      </div>
      ${results.length > 1 ? `<div class="vhist">${results.map((x, i) => `<button class="chip pick ${i === idx ? 'on' : ''}" data-verify-idx="${i}">#${esc(x.cycle ?? i + 1)} ${esc(x.outcome.toLowerCase())}</button>`).join('')}</div>` : ''}`;
  } else {
    result = '<div class="vresult empty"><b>No verification yet</b><p>HARVESTIQ compares solar output before and after each cleaning cycle the ESP32 reports, and says so when the evidence is too weak to conclude anything.</p></div>';
  }

  setHtml($('#verifyBody'), `<ol class="track">${track}</ol><p class="vstatus">${esc(status)}</p>${result}`);
}

