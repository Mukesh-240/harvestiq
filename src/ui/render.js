const TAG = { 'diag-raised': 'ALERT', 'diag-resolved': 'RESOLVED', cleaning: 'CLEANER', 'verification-start': 'VERIFY', 'verification-result': 'VERIFY', connection: 'LINK', telemetry: 'DATA', malformed: 'DATA', 'app-start': 'APP', device: 'DEVICE' };

const NEW_EVENT_MS = 1200;

export function renderTimeline(session, ui, now) {
  const events = session.events.latest(80);
  events.forEach((e) => {
    if (!ui.seenEvents.has(e.id)) ui.seenEvents.set(e.id, now);
  });
  const html = events
    .map((e) => {
      const fresh = now - ui.seenEvents.get(e.id) < NEW_EVENT_MS && ui.seenEvents.size > 1;
      return `<li class="ev ${e.severity}${fresh ? ' new' : ''}"><i class="ev-dot"></i><time>${clock(e.t)}</time><div><span class="tag">${TAG[e.type] ?? 'EVENT'}</span><b>${esc(e.title)}</b>${e.detail ? `<p>${esc(e.detail)}</p>` : ''}</div></li>`;
    })
    .join('');
  setHtml($('#timelineList'), html);
  setText($('#timelineCount'), `${session.events.size} events`);
}

