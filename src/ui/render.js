const CARD_DEFS = [
  { key: 'solar', title: 'SOLAR', color: 'var(--solar)', unit: 'mW', spark: (s) => (isAvailable(s.solar) ? s.solar.powermW : null), foot: 'Power = V x I, measured by the INA219' },
  { key: 'wind', title: 'WIND', color: 'var(--wind)', unit: 'V', spark: (s) => (isAvailable(s.wind) ? s.wind.voltageV : null), foot: 'Generator voltage (measured). Power is an estimate assuming a 200 ohm load' },
  { key: 'piezo', title: 'PIEZO', color: 'var(--piezo)', unit: 'steps', spark: (s) => (isAvailable(s.piezo) ? s.piezo.capVoltageV : null), foot: 'Capacitor voltage trend. Energy is an estimate (1/2 C V^2)' },
  { key: 'battery', title: 'BATTERY', color: 'var(--battery)', unit: '% est.', spark: (s) => (isAvailable(s.battery) ? s.battery.voltageV : null), foot: 'Percentage is estimated from voltage (3.0 V = 0 %, 4.2 V = 100 %); it is not a fuel gauge' },
];

export function mountCards(root) {
  root.innerHTML = CARD_DEFS.map(
    (d) => `<article class="card" data-card="${d.key}" data-state="waiting" style="--c:${d.color}">
      <header><h3>${d.title}</h3><span class="badge muted" data-f="badge"></span></header>
      <div class="metric"><span class="val" data-f="val">-</span><span class="unit" data-f="unit">${d.unit}</span></div>
      <p class="sub" data-f="sub"></p>
      <div class="spark-wrap" data-f="spark"></div>
      <footer>${d.foot}</footer>
    </article>`,
  ).join('');
}

function cardText(key, sensor, cfg) {
  switch (key) {
    case 'solar': return { val: fmt(sensor.powermW, sensor.powermW < 10 ? 1 : 0), sub: `${fmt(sensor.voltageV, 2)} V - ${fmt(sensor.currentmA, 1)} mA` };
    case 'wind': return { val: fmt(sensor.voltageV, 2), sub: sensor.generating ? `about ${fmt(sensor.powermW, 1)} mW (estimate)` : `Idle - below ${fmt(cfg.firmware.windOnV, 2)} V generation level` };
    case 'piezo': return { val: String(sensor.steps), sub: `cap ${fmt(sensor.capVoltageV, 2)} V${sensor.energyuJ === null ? '' : ` - about ${fmt(sensor.energyuJ, 0)} uJ (estimate)`}` };
    default: return { val: String(sensor.pctEstimate), sub: `${fmt(sensor.voltageV, 2)} V measured` };
  }
}

export function renderCards(session, now, ui) {
  const link = session.linkState(now);
  const s = session.latest;
  const demo = session.mode === 'demo';
  for (const d of CARD_DEFS) {
    const el = document.querySelector(`[data-card="${d.key}"]`);
    const sensor = s?.[d.key];
    const state = sensorState(sensor, link, Boolean(s));
    const [btext, bcls] = badge(state, link, demo);
    el.dataset.state = state;
    const b = el.querySelector('[data-f=badge]');
    setText(b, btext);
    b.className = `badge ${bcls}`;
    const val = el.querySelector('[data-f=val]');
    const unit = el.querySelector('[data-f=unit]');
    const sub = el.querySelector('[data-f=sub]');
    const sparkEl = el.querySelector('[data-f=spark]');

    if (state === 'live') {
      const t = cardText(d.key, sensor, session.config);
      if (setText(val, t.val)) {
        if (!REDUCED_MOTION) val.animate([{ transform: 'translateY(3px)', opacity: 0.5 }, { transform: 'none', opacity: 1 }], { duration: 450, easing: 'cubic-bezier(0.22, 0.7, 0.2, 1)' });
      }
      setText(unit, d.unit);
      setText(sub, t.sub);
    } else if (state === 'stale') {
      const t = cardText(d.key, sensor, session.config);
      setText(val, '-');
      setText(unit, '');
      setText(sub, `Last known: ${t.val} ${d.unit} at ${clock(s.t)}`);
    } else if (state === 'unavailable' || state === 'error') {
      setText(val, '-');
      setText(unit, '');
      setText(sub, sensor.reason ?? state);
    } else {
      setText(val, '-');
      setText(unit, '');
      setText(sub, 'Waiting for the first valid reading');
    }

    const sparkHtml =
      state === 'unavailable' || state === 'waiting' || state === 'error'
        ? '<div class="spark-hatch"></div>'
        : sparkline(session.history, d.spark, { now, windowMs: ui.sparkWindowMs, gapMs: session.config.link.staleAfterMs, color: d.color });
    setHtml(sparkEl, sparkHtml);

    if (d.key === 'battery') {
      el.style.setProperty('--p', state === 'live' || state === 'stale' ? String(sensor.pctEstimate / 100) : '0');
    }
  }
}

