// ---------- hero view-model ----------

const clamp01 = (x) => (Number.isFinite(x) ? Math.min(1, Math.max(0, x)) : 0);
const FAULT_STATES = new Set(['DISCONNECTED', 'STALE', 'SUSPECTED FAILURE']);
const BATTERY_WORD = { CHARGING: ' - charging', DISCHARGING: ' - discharging', STABLE: ' - stable', UNKNOWN: '' };

/**
 * Everything the scene may animate, derived from measurements and per-channel health.
 * A source animates only when its reading is valid AND current; a faulty channel gets a warning
 * badge instead of pretending to produce energy.
 */
export function heroView(session, now, ui, health = []) {
  const link = session.linkState(now);
  const s = session.latest;
  const current = link === Link.RECEIVING;
  const cfg = session.config;
  const has = Boolean(s);
  const ch = Object.fromEntries(health.map((c) => [c.id, c]));
  const st = (key) => (has ? sensorState(s[key], link, true) : 'waiting');
  const ok = (key) => current && isAvailable(s?.[key]);
  const fault = (id) => current && FAULT_STATES.has(ch[id]?.status);
  const faultWord = (id) => (ch[id]?.status === 'SUSPECTED FAILURE' ? 'SENSOR SUSPECT' : ch[id]?.status === 'STALE' ? 'SENSOR STALE' : 'SENSOR FAULT');
  const mA = ok('solar') ? s.solar.currentmA : 0;
  const off = (key, id, name) => (fault(id) ? `${name} - ${faultWord(id)}` : st(key) === 'unavailable' ? `${name} - UNAVAILABLE` : st(key) === 'error' ? `${name} - INVALID` : has ? `${name} - OFFLINE` : `${name} - NO DATA`);

  const light = !current ? 'offline' : !isAvailable(s.light) ? 'unavailable' : s.light.label === 'BRIGHT' ? 'bright' : s.light.label === 'NIGHT' ? 'night' : 'dim';
  const rays = ok('light') && !fault('light') ? clamp01((3500 - s.light.raw) / 3200) : 0;
  const windOn = ok('wind') && s.wind.generating && !fault('wind');
  const v = ok('wind') ? s.wind.voltageV : 0;
  const spinLevel = !windOn ? 0 : v > 1.4 ? 4 : v > 1.0 ? 3 : v > 0.6 ? 2 : 1;

  const cleanerState = has && s.cleaner.status === Status.AVAILABLE ? s.cleaner.state : null;
  const cleaning = current && cleanerState === Cleaner.CLEANING;
  const cleanMs = cfg.firmware.cleanMs;
  const elapsed = current && session.cleanerSince !== null ? Math.max(0, now - session.cleanerSince) : 0;
  let cleanerLabel = 'CLEANER - IDLE';
  if (!has || cleanerState === null) cleanerLabel = 'CLEANER - STATE UNKNOWN';
  else if (!current) cleanerLabel = 'CLEANER - OFFLINE';
  else if (cleaning) cleanerLabel = `CLEANING ${Math.min(Math.floor(elapsed / 1000), cleanMs / 1000)}/${cleanMs / 1000} s`;
  else if (cleanerState === Cleaner.COOLDOWN) cleanerLabel = `COOLDOWN ~${Math.max(0, Math.ceil((cfg.firmware.cooldownMs - elapsed) / 1000))} s left`;
  else if (cleanerState === Cleaner.CHECKING) cleanerLabel = 'CONFIRMING LOW OUTPUT';

  const battery = session.batteryState(now);
  const charging = ok('solar') && ok('battery') && mA > cfg.firmware.solarOnMa && !fault('solar') && !fault('battery');
  const demo = session.mode === 'demo';
  const espState = link === Link.RECEIVING ? 'live' : link === Link.STALE ? 'stale' : link === Link.AWAITING_DATA ? 'waiting' : 'offline';
  const espLabel = link === Link.RECEIVING ? (demo ? 'SIMULATED 1 Hz' : 'LIVE 1 Hz') : link === Link.STALE ? 'DATA STALE' : link === Link.AWAITING_DATA ? 'NO DATA YET' : link === Link.CONNECTING ? 'CONNECTING' : 'LIVE DATA UNAVAILABLE';

  return {
    simulated: demo,
    link,
    light,
    rays,
    faults: { solar: fault('solar'), wind: fault('wind'), battery: fault('battery'), light: fault('light') },
    solar: { state: st('solar'), on: ok('solar') && mA > cfg.firmware.solarOnMa, level: mA < 5 ? 1 : mA < 15 ? 2 : 3, label: ok('solar') ? `SOLAR  ${fmt(s.solar.powermW, s.solar.powermW < 10 ? 1 : 0)} mW` : off('solar', 'solar', 'SOLAR') },
    wind: { state: st('wind'), on: windOn, spinLevel, label: ok('wind') ? `WIND  ${fmt(v, 2)} V${windOn ? ` - about ${fmt(s.wind.powermW, 1)} mW` : ' - output not detected'}` : off('wind', 'wind', 'WIND') },
    piezo: { state: st('piezo'), hitAt: ui.lastStepAt, label: ok('piezo') ? `PIEZO  ${s.piezo.steps} steps` : has && s.piezo.status === Status.UNAVAILABLE ? 'PIEZO - NOT CONFIGURED' : off('piezo', 'piezo', 'PIEZO') },
    battery: {
      state: st('battery'),
      charging,
      pct: ok('battery') ? s.battery.pctEstimate : null,
      pctText: ok('battery') ? `~${s.battery.pctEstimate}%` : '',
      estText: ok('battery') ? 'estimate' : '',
      label: ok('battery') ? `BATTERY  ${fmt(s.battery.voltageV, 2)} V${BATTERY_WORD[battery.state]}` : off('battery', 'battery', 'BATTERY'),
    },
    cleaner: { state: cleanerState ?? 'UNKNOWN', on: cleaning, progress: cleaning ? clamp01(elapsed / cleanMs) : 0, label: cleanerLabel },
    esp: { state: espState, label: espLabel },
  };
}
