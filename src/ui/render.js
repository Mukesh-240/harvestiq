// DOM renderers. They only READ session state; nothing here changes telemetry, diagnostics
// or verification. Values from any non-current link state are shown as last-known, never as live.

import { esc, clock } from '../export.js';
import { sparkline } from './charts.js';
import { isAvailable, Link, Status, Cleaner } from '../model.js';

const fmt = (x, d = 1) => (Number.isFinite(x) ? x.toFixed(d) : '-');
const $ = (sel) => document.querySelector(sel);
const REDUCED_MOTION = typeof matchMedia !== 'undefined' && matchMedia('(prefers-reduced-motion: reduce)').matches;

export function setHtml(el, html) {
  if (el && el.__html !== html) {
    el.innerHTML = html;
    el.__html = html;
  }
}
function setText(el, text) {
  if (el && el.textContent !== text) {
    el.textContent = text;
    return true;
  }
  return false;
}

const LINK_TEXT = {
  [Link.NO_CONNECTION]: 'NOT CONNECTED',
  [Link.CONNECTING]: 'CONNECTING',
  [Link.AWAITING_DATA]: 'CONNECTED - NO DATA',
  [Link.STALE]: 'DATA STALE',
  [Link.RECEIVING]: 'RECEIVING',
};

function sensorState(sensor, link, hasData) {
  if (!hasData) return 'waiting';
  if (sensor.status === Status.ERROR) return 'error';
  if (sensor.status === Status.UNAVAILABLE) return 'unavailable';
  return link === Link.RECEIVING ? 'live' : 'stale';
}

function badge(state, link, demo) {
  switch (state) {
    case 'live': return demo ? ['SIMULATED', 'sim'] : ['AVAILABLE', 'ok'];
    case 'stale': return [link === Link.STALE ? 'STALE' : link === Link.AWAITING_DATA ? 'WAITING' : 'OFFLINE', 'warn'];
    case 'unavailable': return ['UNAVAILABLE', 'muted'];
    case 'error': return ['ERROR', 'crit'];
    default: return ['NO DATA', 'muted'];
  }
}

// ---------- header ----------

export function renderHeader(session, now, { serialSupported, mode, demo, demoSpeed = 1 }) {
  const link = session.linkState(now);
  const isDemoSession = session.mode === 'demo';
  const health = session.health(now);
  document.body.dataset.mode = mode;
  document.body.dataset.link = link;

  const everLost = session.connection.everConnected && link === Link.NO_CONNECTION;
  let linkText = LINK_TEXT[link];
  if (everLost) linkText = 'DISCONNECTED';
  if (isDemoSession && link === Link.NO_CONNECTION && !everLost) linkText = 'NO SCENARIO RUNNING';
  if (isDemoSession && link === Link.RECEIVING) linkText = demo?.state === 'paused' ? 'SIMULATION PAUSED' : 'SIMULATED DATA';
  if (!isDemoSession && link === Link.RECEIVING) linkText = 'LIVE FROM ESP32';
  const lvl = link === Link.RECEIVING ? (isDemoSession ? 'sim' : 'ok') : link === Link.NO_CONNECTION || link === Link.CONNECTING ? 'muted' : 'warn';
  const badgeHtml = `<span class="badge ${lvl}"><i></i>${esc(linkText)}</span>`;
  setHtml($('#linkBadge'), badgeHtml);
  setHtml($('#heroLink'), badgeHtml);

  const age = session.lastTelemetryAt === null ? null : Math.max(0, Math.round((now - session.lastTelemetryAt) / 1000));
  const lastText = age === null ? 'No valid data received yet' : `Last valid data ${clock(session.lastTelemetryAt)} (${age < 120 ? `${age} s ago` : `${Math.round(age / 60)} min ago`})`;
  setText($('#lastData'), lastText);
  setText($('#heroLast'), lastText);
  setHtml($('#health'), `<span class="health-chip ${health.level}"><small>SYSTEM</small><b>${esc(health.label)}</b></span>`);

  const connected = session.connection.state === 'connected';
  document.querySelectorAll('[data-action="connect"]').forEach((el) => {
    el.hidden = mode === 'demo' || connected;
    el.disabled = !serialSupported || link === Link.CONNECTING;
    el.title = serialSupported ? '' : 'Web Serial needs Chrome or Edge';
    setText(el, link === Link.CONNECTING ? 'Choose a port...' : everLost ? 'Reconnect ESP32' : 'Connect ESP32');
  });
  document.querySelectorAll('[data-action="disconnect"]').forEach((el) => {
    el.hidden = mode === 'demo' || !connected;
  });
  $('#serialWarn').hidden = serialSupported || mode === 'demo';

  const sim = $('#simBanner');
  sim.hidden = !isDemoSession || mode !== 'demo';
  setHtml(sim, isDemoSession ? `<b>SIMULATED DATA</b><span>${esc(session.label || 'Demo')} - generated by software, not measured from hardware</span>` : '');
  document.querySelectorAll('[data-mode-btn]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.modeBtn === mode)));

  $('#demoBar').hidden = mode !== 'demo';
  const toggle = $('#demoToggle');
  if (!demo) {
    setText(toggle, 'Start');
    toggle.title = 'Start the selected scenario (nothing runs until you press this)';
  } else if (demo.finished) {
    setText(toggle, 'Replay');
    toggle.title = 'Scenario complete - replay it from the start';
  } else if (demo.state === 'running') {
    setText(toggle, 'Pause');
    toggle.title = 'Freeze simulated time';
  } else {
    setText(toggle, 'Resume');
    toggle.title = 'Continue the simulation';
  }
  $('#demoReset').disabled = !demo;
  $('#demoReset').title = demo ? 'Restart this scenario and clear its simulated alerts' : 'Nothing to reset - no scenario has been started';
  document.querySelectorAll('[data-speed]').forEach((b) => {
    b.setAttribute('aria-pressed', String(Number(b.dataset.speed) === (demo ? demo.speed : demoSpeed)));
  });
  const select = $('#scenarioSelect');
  if (demo && select.value !== demo.scenarioId) select.value = demo.scenarioId;
}

